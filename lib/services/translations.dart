  static String translate(String text) {
    if (currentLanguage == 'fr') return text;

    final trimmed = text.trim();
    if (trimmed.isEmpty) return text;

    // 1. Recherche directe exacte
    final direct = _en[trimmed];
    if (direct != null) {
      return _preserveWhitespaceAndCase(text, trimmed, direct);
    }

    // 2. Recherche insensible à la casse
    final lowerTrimmed = trimmed.toLowerCase();
    for (final entry in _en.entries) {
      if (entry.key.toLowerCase() == lowerTrimmed) {
        return _preserveWhitespaceAndCase(text, trimmed, entry.value);
      }
    }

    // 3. Gestion de ponctuation et symboles en fin de chaîne (: ! ? * > → ... … 👋 +)
    final trailingPatterns = [
      '...', '…', ' >', '>', ' →', '→', ' 👋', '👋', ' +', '+', ':', '!', '?', '*', '•'
    ];
    for (final pattern in trailingPatterns) {
      if (trimmed.endsWith(pattern)) {
        final core = trimmed.substring(0, trimmed.length - pattern.length).trim();
        final coreTr = _en[core] ?? _lookupCaseInsensitive(core);
        if (coreTr != null) {
          final translated = '$coreTr$pattern';
          return _preserveWhitespaceAndCase(text, trimmed, translated);
        }
      }
    }

    // 4. Gestion de préfixe ou suffixe entre parenthèses
    if (trimmed.startsWith('(') && trimmed.endsWith(')')) {
      final inner = trimmed.substring(1, trimmed.length - 1).trim();
      final innerTr = _en[inner] ?? _lookupCaseInsensitive(inner);
      if (innerTr != null) {
        return _preserveWhitespaceAndCase(text, trimmed, '($innerTr)');
      }
    }

    return text;
  }

  static String? _lookupCaseInsensitive(String text) {
    final lower = text.toLowerCase().trim();
    for (final entry in _en.entries) {
      if (entry.key.toLowerCase().trim() == lower) {
        return entry.value;
      }
    }
    return null;
  }

  static String _preserveWhitespaceAndCase(String original, String trimmed, String translated) {
    String result = translated;
    
    // Si l'original était tout en majuscules (ex: "VALEUR DU STOCK")
    if (trimmed.length > 2 && trimmed == trimmed.toUpperCase() && trimmed != trimmed.toLowerCase()) {
      result = result.toUpperCase();
    }

    // Préserver les espaces au début et à la fin
    if (original.startsWith(' ') && original.endsWith(' ')) {
      return ' $result ';
    } else if (original.startsWith(' ')) {
      return ' $result';
    } else if (original.endsWith(' ')) {
      return '$result ';
    }
    return result;
  }
